"""Structure builders for aiida-uranium-workflow."""

from __future__ import annotations

from .common import STATIC_DIR
from .yamlio import read_yaml
from typing import Any
from pathlib import Path

import argparse
import sys

STRUCTURE_YML = STATIC_DIR / "structure.yml"


def classify_structure_ref(ref: Any) -> tuple[str, Any]:
    """Classify one ``static.structure`` entry.

    Returns ``(kind, value)`` with ``kind`` in ``{"pk", "uuid", "name"}``:

    * ``{"pk": 12345}`` / ``{"uuid": "..."}`` — explicit dict form (the
      same convention as ``extra_files`` in the SCF presets);
    * ``12345`` / ``"12345"`` — an integer pk, i.e. an existing
      ``StructureData`` node in the profile;
    * ``"3f2a…-…"`` — a UUID (dashed or bare 32 hex characters);
    * anything else — a name from ``static/structure.yml``.

    The identifier forms let ``input.json`` point at structures that were
    imported and stored once (e.g. from POSCAR / CIF files) instead of
    re-generating them from the registry.
    """
    if isinstance(ref, dict):
        has_pk = ref.get("pk") is not None
        ident = ref.get("pk") if has_pk else ref.get("uuid")
        if ident is None:
            raise ValueError(
                f"structure reference dict must contain 'pk' or 'uuid', got {ref!r}"
            )
        if has_pk:
            return "pk", int(ident) if str(ident).isdigit() else ident
        from uuid import UUID

        return "uuid", str(UUID(str(ident)))

    if isinstance(ref, bool):  # bool is an int subclass — never a pk here
        raise TypeError(f"invalid structure reference {ref!r}")
    if isinstance(ref, int):
        return "pk", ref
    if not isinstance(ref, str):
        raise TypeError(
            "structure references must be a registry name, a pk, a uuid or "
            f"a {{'pk'|'uuid': ...}} dict, got {type(ref).__name__}"
        )

    text = ref.strip()
    if text.isdigit():
        return "pk", int(text)
    try:  # dashed or bare-hex UUID; registry names never parse as one
        from uuid import UUID

        return "uuid", str(UUID(text))
    except (ValueError, AttributeError, TypeError):
        return "name", ref


def load_structure_node(ref: Any):
    """Return the stored ``StructureData`` referenced by ``ref``.

    Returns ``None`` when ``ref`` is a registry name (nothing to load
    yet). Raises when a pk / uuid does not resolve to a ``StructureData``.
    """
    kind, value = classify_structure_ref(ref)
    if kind == "name":
        return None

    from aiida import orm

    try:
        node = orm.load_node(value)
    except Exception as exc:  # noqa: BLE001 — NotExistent / ValueError
        raise ValueError(
            f"structure {kind} {value!r} could not be loaded from the profile: {exc}"
        ) from exc
    if not isinstance(node, orm.StructureData):
        raise TypeError(
            f"structure {kind} {value!r} is a {type(node).__name__}, not a "
            "StructureData — store it with "
            "`StructureData(ase=ase.io.read(<file>)).store()`."
        )
    return node


def structure_ref_label(ref: Any) -> str:
    """Short human-readable label for a structure reference (for logs)."""
    kind, value = classify_structure_ref(ref)
    if kind == "pk":
        return f"pk{value}"
    if kind == "uuid":
        return f"uuid:{str(value)[:8]}"
    return str(value)


def build_structure(atom_name: str, *, registry: dict[str, Any] | None = None):
    """Build an ASE Atoms object from a static entry via pyxtal.

    Returns
    -------
    ase.Atoms
        An ASE ``Atoms`` instance generated by ``pyxtal`` from the
        spacegroup / Wyckoff-position / lattice parameters declared in
        ``static/structure.yml``.

    Notes
    -----
    Uses ``pyxtal.pyxtal.from_spg_wps_rep``:
        from pyxtal import pyxtal
        cry = pyxtal()
        cry.from_spg_wps_rep(spg, wps, [a, x1, x2, ...], [species_per_wp])
        return cry.to_ase()

    ``elements`` is a per-Wyckoff-position species list (length must
    match ``wickoff_position``); ``x`` packs one lattice parameter
    followed by fractional coordinates for each Wyckoff site.
    """
    # Imports are deferred so this module is importable even without
    # heavy dependencies (ase / pyxtal) for code paths that only need
    # the YAML loader.
    from pyxtal import pyxtal

    if registry is None:
        registry = read_yaml(STRUCTURE_YML)

    if atom_name not in registry:
        raise KeyError(f"Structure '{atom_name}' not found in {STRUCTURE_YML}")
    entry = registry[atom_name]

    spg = int(entry["spacegroup"])
    # The YAML key is ``wickoff_position`` (typo-tolerant alias);
    # pyxtal expects ``wps`` (Wyckoff positions).
    wps = entry.get("wps") or entry.get("wickoff_position")
    if not wps:
        raise KeyError(f"Structure '{atom_name}' is missing 'wps' / 'wickoff_position'")

    elements = entry["elements"]
    if len(elements) != len(wps):
        raise ValueError(
            f"Structure '{atom_name}': 'elements' (len={len(elements)}) must "
            f"match 'wickoff_position' (len={len(wps)})"
        )

    x = entry["x"]
    if not isinstance(x, list) or len(x) < 1:
        raise ValueError(
            f"Structure '{atom_name}': 'x' must be a non-empty list"
        )

    # ``x`` mirrors ``gamma0_uranium.py``'s shape:
    #     x = cell_params + [c for coords in site_coords for c in coords]
    # The leading entries are the lattice parameters
    # (a, c for SG 129; a for cubic; a, b, c for orthorhombic; …),
    # the trailing ``len(wps)`` entries are the free fractional
    # coordinates, one per Wyckoff site. The number of lattice
    # parameters is therefore ``len(x) - len(wps)``.
    n_lattice = len(x) - len(wps)
    a = [float(v) for v in x]

    cry = pyxtal()
    cry.from_spg_wps_rep(spg, wps, a, list(elements))
    return cry.to_ase()


def write_cif(
    atom_name: str,
    output_dir: str | Path = ".",
    *,
    registry: dict[str, Any] | None = None,
) -> Path:
    """Build ``atom_name`` and write it to ``<output_dir>/<safe_name>.cif``.

    Structure keys may contain path separators (e.g. ``U-X/FCC``); these
    are rewritten to ``__`` so the resulting filename stays flat in
    ``output_dir``. ``U-X/FCC`` → ``U-X__FCC.cif``.

    Parameters
    ----------
    atom_name
        Key in ``static/structure.yml``.
    output_dir
        Directory the CIF file will be written to. Created if it does
        not exist.
    registry
        Optional pre-loaded structure registry (used by tests).

    Returns
    -------
    pathlib.Path
        Absolute path of the written ``.cif`` file.
    """
    import ase.io

    atoms = build_structure(atom_name, registry=registry)
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    safe_name = atom_name.replace("/", "__")
    out_path = (out_dir / safe_name).with_suffix(".cif").resolve()
    ase.io.write(str(out_path), atoms, format="cif")
    return out_path


def _build_arg_parser() -> argparse.ArgumentParser:
    """Build the CLI argument parser for :func:`main`."""
    p = argparse.ArgumentParser(
        prog="aiida-uranium-structure-cif",
        description=(
            "Generate CIF files for the structures registered in "
            "static/structure.yml."
        ),
    )
    p.add_argument(
        "names",
        nargs="*",
        default=[],
        help=(
            "One or more structure names as listed in static/structure.yml "
            "(e.g. 'bcc-uranium' 'bcc-uranium-0K'). Optional when --list is given."
        ),
    )
    p.add_argument(
        "-o",
        "--output-dir",
        dest="output_dir",
        default=".",
        help="Directory to write the .cif files into (default: current directory).",
    )
    p.add_argument(
        "--list",
        action="store_true",
        dest="list_only",
        help="List the registered structures and exit.",
    )
    return p


def main(argv: list[str] | None = None) -> int:
    """CLI entry point: build the requested structures and write CIF files.

    Examples
    --------
    Generate a single CIF file in the current directory::

        python -m aiida_uranium_workflow.utils.structure bcc-uranium

    Generate several CIF files in a specific directory::

        python -m aiida_uranium_workflow.utils.structure \\
            bcc-uranium bcc-uranium-0K -o ./cifs

    Inspect the registered structures without writing anything::

        python -m aiida_uranium_workflow.utils.structure --list
    """
    args = _build_arg_parser().parse_args(argv)
    registry = read_yaml(STRUCTURE_YML)

    if args.list_only:
        print("Available structures:")
        for name in registry:
            print(f"  - {name}")
        return 0

    if not args.names:
        print(
            "[structure] error: at least one structure name is required "
            "(use --list to inspect registered structures).",
            file=sys.stderr,
        )
        return 1

    written: list[Path] = []
    for name in args.names:
        try:
            path = write_cif(name, output_dir=args.output_dir, registry=registry)
        except (KeyError, ValueError, NotImplementedError) as exc:
            print(f"[structure] error: {exc}", file=sys.stderr)
            return 1
        print(f"[structure] wrote {path}")
        written.append(path)

    if not written:
        print("[structure] no structure written", file=sys.stderr)
        return 1
    print(f"[structure] {len(written)} CIF file(s) generated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
